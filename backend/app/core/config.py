from pydantic_settings import BaseSettings, SettingsConfigDict
from typing import Optional

class Settings(BaseSettings):
    PROJECT_NAME: str = "Kipatik"
    API_V1_STR: str = "/api/v1"
    
    # Database
    DATABASE_URL: str = "postgresql+asyncpg://user:password@db:5432/diplom"
    
    # Redis / Celery
    REDIS_URL: str = "redis://redis:6379/0"
    CELERY_BROKER_URL: str = "redis://redis:6379/0"
    CELERY_RESULT_BACKEND: str = "redis://redis:6379/0"
    
    # Security
    SECRET_KEY: str = "SUPER_SECRET_KEY_CHANGE_ME" # В .env потом
    ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 60 * 24 * 7 # 7 days
    
    # Шифрование токенов Git-провайдеров при хранении.
    # Если не задать явно, ключ выводится из SECRET_KEY.
    TOKEN_ENCRYPTION_KEY: str = ""

    # Периодическая сверка Git-интеграции (reconcile)
    GIT_SYNC_ENABLED: bool = True
    GIT_SYNC_INTERVAL_SECONDS: int = 300
    GIT_SYNC_MAX_PAGES: int = 5          # сколько страниц докачивать за проход
    GIT_SYNC_PAGE_SIZE: int = 100
    GIT_SYNC_SINCE_DAYS: int = 90        # глубина истории при первой сверке
    GIT_HTTP_TIMEOUT_SECONDS: float = 20.0
    GIT_HTTP_MAX_RETRIES: int = 3

    # Публичный адрес сервера. Используется для авторегистрации вебхуков:
    # провайдер шлёт события на {PUBLIC_BASE_URL}/api/v1/git/webhook/{repository_id}
    PUBLIC_BASE_URL: str = "http://localhost:8000"

    # Авторегистрация вебхуков через API провайдера
    GIT_WEBHOOK_AUTO_REGISTER: bool = True

    # ------------------------------------------------------------------ #
    # OAuth-приложения (предпочтительный способ авторизации)
    # Client ID / Secret выдаёт сам провайдер при регистрации приложения.
    # Пока они не заданы, доступен запасной путь — Personal Access Token.
    # ------------------------------------------------------------------ #
    GITHUB_CLIENT_ID: str = ""
    GITHUB_CLIENT_SECRET: str = ""

    GITLAB_CLIENT_ID: str = ""
    GITLAB_CLIENT_SECRET: str = ""
    # Для self-hosted: https://gitlab.company.ru
    GITLAB_HOST: str = "https://gitlab.com"

    GITEA_CLIENT_ID: str = ""
    GITEA_CLIENT_SECRET: str = ""
    GITEA_HOST: str = ""

    BITBUCKET_CLIENT_ID: str = ""
    BITBUCKET_CLIENT_SECRET: str = ""

    # Куда провайдер возвращает пользователя после согласия.
    # Это адрес ФРОНТЕНДА, а не API.
    OAUTH_FRONTEND_REDIRECT: str = "http://localhost:3000/profile"
    # Время жизни подписанного state (секунды) — окно на подтверждение
    OAUTH_STATE_TTL_SECONDS: int = 600

    # ------------------------------------------------------------------ #
    # Оценка прогресса задачи (ЛР №2)
    #
    # Модуль правил, нейросеть не требуется.
    # ------------------------------------------------------------------ #
    PROGRESS_ENABLED: bool = True

    # Ожидаемый объём изменений на задачу в строках, если калибровать
    # не по чему. Константа 26 из лабораторной — размер одного коммита
    # в стороннем датасете GitHub-issues, а у нас на задачу суммируются
    # все её коммиты, поэтому дефолт задан заметно больше.
    PROGRESS_DEFAULT_EXPECTED_VOLUME: int = 200

    # Сколько задач с коммитами нужно, чтобы доверять калибровке по проекту.
    # Оцениваемая задача из выборки исключается, поэтому на калибровку нужно
    # на одну задачу больше. На меньшей выборке перцентиль — шум.
    PROGRESS_MIN_TASKS_FOR_CALIBRATION: int = 3

    # Сила априора при калибровке объёма. Вес данных равен
    # n / (n + PROGRESS_CALIBRATION_PRIOR_STRENGTH): чем больше задач
    # в выборке, тем ближе оценка к их фактическому перцентилю. При
    # одной наблюдаемой задаче данные получают четверть веса, остальное
    # берётся из PROGRESS_DEFAULT_EXPECTED_VOLUME — иначе оценка по
    # единственному соседу совпадает с его же объёмом.
    PROGRESS_CALIBRATION_PRIOR_STRENGTH: int = 3

    # Сколько дней показывать в динамике прогресса
    PROGRESS_HISTORY_DAYS: int = 30

    # ------------------------------------------------------------------ #
    # Модели анализа кода (ЛР №1 и №3)
    #
    # Модуль импортируется лениво, поэтому даже выключенная модель
    # не тянет за собой torch и не читает гигабайтные веса при старте.
    # ------------------------------------------------------------------ #
    CODE_MODEL_ENABLED: bool = True

    # Папка с моделями анализа кода. Пустая — искать рядом с кодом:
    # тогда путь не зависит от того, откуда запущен сервер. Раньше
    # здесь стоял относительный путь, и запуск не из папки backend
    # находил артефакты и молча работал без моделей.
    #
    # Внутри неё папка code_model с артефактами обеих моделей:
    #   code_model/commit_tracer.pt
    #   code_model/type_classifier.pt
    #   code_model/<имя модели>/        конфиг и словарь
    #   code_model/progress_estimator.py
    CODE_MODEL_DIR: str = ""
    # Относительное имя файла весов внутри папки weights/ своей модели
    CODE_MODEL_TRACER_FILE: str = "commit_tracer.pt"
    CODE_MODEL_CLASSIFIER_FILE: str = "type_classifier.pt"

    # auto | cpu | cuda
    CODE_MODEL_DEVICE: str = "auto"

    # Порог привязки коммита к задаче.
    # Значение не взято «на глаз»: замер на 5 примерах с посторонними
    # кандидатами дал разрыв 0.13..0.48 между посторонними и верными
    # задачами, середина разрыва — около 0.30. Порог 0.55 из более ранней
    # оценки отбрасывал пятую часть верных совпадений.
    # Ниже порога решение остаётся за человеком: модель лишь предлагает.
    CODE_MODEL_TRACE_THRESHOLD: float = 0.30

    # Сколько задач проекта рассматривать при подборе. Модель считает
    # вектор для каждого кандидата, поэтому список ограничен.
    CODE_MODEL_TRACE_LIMIT: int = 20

    # Бюджет времени на один коммит при массовом прогоне. Модель на CPU
    # занимает сотни миллисекунд на коммит, и без ограничения прогон
    # сотни коммитов растянулся бы на минуты.
    CODE_MODEL_TRACE_BUDGET_SECONDS: float = 5.0

    # Трассировка по смыслу при периодической сверке.
    # Каждый коммит — это запрос в модель (сотни миллисекунд на CPU),
    # поэтому по умолчанию выключено: сверка не должна надолго
    # задерживаться из-за необязательного шага.
    GIT_TRACE_ON_SYNC: bool = False
    GIT_TRACE_SYNC_LIMIT: int = 10

    # Догружать ли правки прямо во время трассировки. По умолчанию нет:
    # это запрос к API провайдера на каждый коммит без правок, и молча
    # съедать лимиты нельзя. Обычно правки заполняются заранее через
    # POST /api/v1/git/{id}/patches/backfill.
    GIT_TRACE_FETCH_PATCHES: bool = False

    # Определять тип коммита (ЛР №3) при привязке к задаче.
    #
    # Считается в том же запросе, что и привязка, поэтому первый вызов
    # на не прогретой модели занимает секунды: модель прогревается при
    # старте приложения отдельной фоновой задачей.
    CODE_MODEL_CLASSIFY: bool = True

    # ------------------------------------------------------------------ #
    # Тексты изменений (нужны моделям анализа кода)
    #
    # Правки запрашиваются отдельным запросом на каждый коммит: списком
    # их не отдаёт ни один провайдер. Поэтому по умолчанию выключено —
    # иначе синхронизация проекта на сотню коммитов превратится в сотню
    # запросов и упрётся в лимиты.
    # ------------------------------------------------------------------ #
    GIT_FETCH_PATCHES: bool = False

    # Максимум символов правки на файл. Модель всё равно обрезает вход до
    # 256 токенов, а целые патчи бывают на сотни килобайт.
    GIT_MAX_PATCH_CHARS: int = 4000

    # Сколько коммитов дозаполнять за один запуск. Запрос на коммит —
    # это один вызов к API провайдера, поэтому ограничение обязательно.
    GIT_PATCH_BACKFILL_LIMIT: int = 50

    # Пауза между запросами при дозаполнении, чтобы не упереться в лимиты
    GIT_PATCH_BACKFILL_DELAY: float = 0.3

    # ------------------------------------------------------------------ #
    # Руководства пользователя и администратора
    #
    # Тексты лежат в docs/ рядом с backend и отдаются по адресу
    # /docs/<файл>. Та же папка доступна в репозитории как обычный
    # Markdown, поэтому в приложении нет второй копии текста.
    #
    # Раздача по умолчанию выключена: руководство администратора
    # перечисляет секреты, переменные окружения и известные слабые
    # места развёртывания. Выкладывать его наружу нужно осознанно.
    # ------------------------------------------------------------------ #
    SERVE_DOCS: bool = False

    # Где искать папку с руководствами. Пусто — искать рядом с
    # приложением в разумных местах; задаётся в контейнере, где
    # структура папок другая, чем в репозитории.
    DOCS_DIR: str = ""

    model_config = SettingsConfigDict(env_file=".env", case_sensitive=True)

settings = Settings()
