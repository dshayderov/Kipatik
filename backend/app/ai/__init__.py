"""Модуль моделей анализа кода.

Устройство папки ровно такое:

  api.py        единая точка работы с моделями: реестр включения,
                модель трассировки (лабораторная работа №1), модель
                типов коммитов (лабораторная работа №3) и маршруты
  code_model/   артефакты и модуль правил:
                  commit_tracer.pt                        веса трассировки
                  type_classifier.pt                      веса типов
                  progress_estimator.py                   модуль правил
                  paraphrase-multilingual-mpnet-base-v2/  конфиг и словарь
  task_model/   зарезервирован под модель анализа задач, пока пуст

Что уехало из папки и почему
---------------------------

Модуль `api.py` не про нейросети, поэтому в `app/ai` ему не место.
Каждый переехал туда, где ему привычнее:

  app/models/ai_settings.py   таблица настроек включения моделей
  app/tasks/nlp_service.py    разбор текста задачи по ключевым словам
  app/tasks/progress.py       сборка прогресса по данным базы
  app/git/commit_types.py     запись типа коммита в базу

Файл `__init__.py` сохранён: остальные папки проекта (`app/core`,
`app/tasks`, `app/git`) тоже его имеют, и без него `app.ai`
превращается в пакет пространства имён, что уже приводило к ошибке
импорта при совпадении элементов в путях поиска.
"""